"""Truncated free semigroups of a variety, and the countermodels they give.

Among semigroups a law is a pair of words. For laws P and k generators, the
truncated free semigroup S_n is the free semigroup on k generators of the
variety of P with every product of n or more letters made 0: the words of
length below n and a zero, modulo the congruence generated by the instances
of the laws of P, a side of length n or more being the zero. It is computed
by closing the instances under multiplication by the generators, a finite
computation. S_n satisfies P and is generated by the k generators, so it is
a quotient of the free semigroup of the variety, and a law of k variables
that fails in S_n at the generators does not follow from P.

Such countermodels can be far larger than any model search reaches: for
x^3 = x^4, x^3 = y x^3 and x^2 y = y x y^2, the law x^3 = y^2 z x fails in
S_8, of 271 elements, and in its Rees quotient by the elements that do not
divide y^2 z x at the generators, of 39, the size returned. The countermodels
are checked against the laws.
"""

from __future__ import annotations

import time
from collections.abc import Iterator, Sequence
from itertools import product

from explorations.equational_theories.magma import Equation, Magma

Word = tuple[int, ...]


def words(equation: Equation) -> tuple[Word, Word]:
    """The two words of a law, the variables numbered by first occurrence."""
    names: dict[str, int] = {}
    return tuple(tuple(names.setdefault(v, len(names)) for v in side.factors()) for side in (equation.lhs, equation.rhs))


class OutOfTime(Exception):
    pass


def _check(deadline: float | None) -> None:
    if deadline is not None and time.monotonic() > deadline:
        raise OutOfTime


def _instances(
        law: tuple[Word, Word],
        by_length: dict[int, list[str]],
        n: int,
        deadline: float | None = None,
) -> Iterator[tuple[str, str]]:
    """The instances of the law by words of length below n of which a side
    is shorter than n (the others are 0 = 0).

    A side of length n or more is 0 whatever its words, so the words of a
    variable that occurs only in such sides do not matter: it gets one word
    of each length, and once its sides are that long, only the shortest.
    Instances that differ only there are given once. Raises OutOfTime after
    the deadline.
    """
    u, v = law
    count = max(u + v) + 1
    occurrences = [(u.count(x), v.count(x)) for x in range(count)]

    def lengths(x: int, left: int, right: int) -> Iterator[tuple[int, ...]]:
        if x == count:
            yield ()
            return
        # Only in sides already long: its length changes nothing.
        irrelevant = all(side >= n for side, o in zip((left, right), occurrences[x]) if o)
        for length in range(1, 2 if irrelevant else n):
            a, b = left + length * occurrences[x][0], right + length * occurrences[x][1]
            if min(a, b) >= n:
                break
            for rest in lengths(x + 1, a, b):
                yield (length,) + rest

    seen = set()
    for k, chosen in enumerate(lengths(0, 0, 0)):
        if k % 4096 == 0:
            _check(deadline)
        short = [sum(chosen[x] for x in side) < n for side in (u, v)]
        relevant = [any(x in side for side, s in zip((u, v), short) if s) for x in range(count)]
        key = (tuple(short), tuple(length if r else 0 for length, r in zip(chosen, relevant)))
        if key in seen:
            continue
        seen.add(key)
        choices = [by_length[length] if r else by_length[length][:1] for length, r in zip(chosen, relevant)]
        for j, subs in enumerate(product(*choices)):
            if j % 4096 == 4095:
                _check(deadline)
            yield "".join(subs[x] for x in u), "".join(subs[x] for x in v)


class Truncated:
    """S_n for the laws and k generators, the letters a, b, ...: its
    elements, numbered, with 0 the zero, and its Cayley table. Raises
    OutOfTime if it is not done by the deadline."""

    def __init__(
            self,
            laws: Sequence[tuple[Word, Word]],
            generators: int,
            n: int,
            deadline: float | None = None,
    ) -> None:
        letters = "abcdefghij"[:generators]
        self.n = n
        all_words = ["0"] + ["".join(p) for m in range(1, n) for p in product(letters, repeat=m)]
        index = {w: i for i, w in enumerate(all_words)}
        by_length = {m: [w for w in all_words[1:] if len(w) == m] for m in range(1, n)}
        parent = list(range(len(all_words)))

        def find(i: int) -> int:
            while parent[i] != i:
                parent[i] = parent[parent[i]]
                i = parent[i]
            return i

        node = lambda w: index[w] if len(w) < n else 0

        def union(a: int, b: int) -> bool:
            a, b = find(a), find(b)
            if a == b:
                return False
            if b == 0:
                a, b = b, a
            parent[b] = a
            return True

        for law in laws:
            for left, right in _instances(law, by_length, n, deadline):
                union(node(left), node(right))
        # Close under multiplication by the generators on either side: the
        # class of w c, or of c w, depends only on the class of w.
        changed = True
        while changed:
            changed = False
            _check(deadline)
            for side in (0, 1):
                seen: dict[tuple[int, str], int] = {}
                for i, w in enumerate(all_words):
                    for c in letters:
                        p = 0 if i == 0 else node(w + c if side == 0 else c + w)
                        key = (find(i), c)
                        if key in seen:
                            changed |= union(seen[key], p)
                        else:
                            seen[key] = p
        representatives = sorted({find(i) for i in range(len(all_words))})
        number = {r: j for j, r in enumerate(representatives)}
        # "0" is the zero's word, numbered 0 like the long words.
        self.element = lambda w: number[find(node(w))]
        self.names = [all_words[r] for r in representatives]
        self.zero = self.element("0")
        self.table = tuple(
            tuple(self.zero if self.zero in (j, k) else self.element(a + b) for k, b in enumerate(self.names))
            for j, a in enumerate(self.names)
        )

    def at_generators(self, side: Word) -> int:
        return self.element("".join("abcdefghij"[x] for x in side))

    def divisor_quotient(self, target: int) -> Magma:
        """The Rees quotient by the elements that do not divide `target`: its
        divisors and the zero, the products of which that are not divisors
        being the zero."""
        size = len(self.names)
        table = self.table
        left = [{s} | {table[x][s] for x in range(size)} for s in range(size)]
        keep = sorted({s for s in range(size) if any(target == u or target in table[u] for u in left[s])} | {self.zero})
        pos = {s: j for j, s in enumerate(keep)}
        return Magma(len(keep), tuple(tuple(pos.get(table[x][y], pos[self.zero]) for y in keep) for x in keep))


def truncated_countermodels(
        premise: Sequence[Equation],
        laws: Sequence[Equation],
        max_words: int,
        max_generators: int = 4,
        time_limit: float | None = 30,
) -> list[Magma]:
    """Countermodels to the premise implying each of the laws, from the
    truncated free semigroups of the premise's variety: for each number k of
    variables up to `max_generators`, S_n for every n whose words of length
    below n number at most `max_words`, until the laws of k variables fail.
    Each countermodel is the Rees quotient of S_n by the non-divisors of a
    side of a failing law, checked against the premise and the law. After
    `time_limit` seconds, the countermodels found so far are returned: a
    premise with many instances, such as x = y z w u v t, can take far
    longer."""
    deadline = None if time_limit is None else time.monotonic() + time_limit
    premise_words = [w for w in map(words, premise) if w[0] != w[1]]
    found: list[Magma] = []
    by_count: dict[int, list[Equation]] = {}
    for law in laws:
        u, v = words(law)
        if u != v:
            by_count.setdefault(max(u + v) + 1, []).append(law)
    for count, group in sorted(by_count.items()):
        if count > max_generators:
            continue
        left = list(group)
        n = 2
        while left and sum(count ** m for m in range(1, n + 1)) <= max_words:
            n += 1
            try:
                semigroup = Truncated(premise_words, count, n, deadline)
            except OutOfTime:
                return found
            for law in list(left):
                u, v = words(law)
                a, b = semigroup.at_generators(u), semigroup.at_generators(v)
                if a == b:
                    continue
                magma = semigroup.divisor_quotient(b if a == semigroup.zero else a)
                if all(magma.holds(eq) for eq in premise) and not magma.holds(law):
                    found.append(magma)
                left.remove(law)
    return found
